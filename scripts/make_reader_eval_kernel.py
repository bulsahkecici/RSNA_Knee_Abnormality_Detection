"""Build a private, internet-off Kaggle kernel that scores the public ConvNeXt reader on gold-58.

Usage: python scripts/make_reader_eval_kernel.py --slug rsna-reader-gold-eval-20261014

The reader is goodpjw2008/rsna-knee-2-5d-convnext-reader (Apache-2.0; trained on competition
data with the mean of four CC0 report-label tables; gold-58 not used for training). The kernel
runs the reader's own infer.py on the 58 gold training studies, straight from DICOM, and writes
reader-gold.csv plus the sha256 of every reader file (to pin them in a later submission kernel).
It never writes submission.csv. Gold-only: the reader's weak predictions would be in-sample.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
READER = "goodpjw2008/rsna-knee-2-5d-convnext-reader"

ENTRY = r'''#!/usr/bin/env python3
"""Score the public ConvNeXt reader on gold-58. Generated by scripts/make_reader_eval_kernel.py."""
import hashlib, json, os, subprocess, sys
from pathlib import Path

GOLD = __GOLD__
INPUTS = Path("/kaggle/input")
WORK = Path("/kaggle/working")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


reader = [p.parent for p in INPUTS.rglob("infer.py") if (p.parent / "cnxt_v0_fold0.pt").is_file()]
assert len(reader) == 1, reader
reader = reader[0]
comp = [p.parent for p in INPUTS.rglob("train_series.csv") if (p.parent / "train_series").is_dir()]
assert len(comp) == 1, comp
comp = comp[0]
files = {p.name: sha256(p) for p in sorted(reader.iterdir()) if p.is_file()}
(WORK / "reader-files.json").write_text(json.dumps({"dataset": "__READER__", "files": files}, indent=2))
wheels = [str(p) for p in reader.glob("pylibjpeg*.whl")
          if f"cp{sys.version_info.major}{sys.version_info.minor}" in p.name or "py3-none" in p.name]
if wheels:
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "--no-index", "--no-deps", *wheels], check=False)
sys.path.insert(0, str(reader))
os.chdir(WORK)
import infer  # noqa: E402  (the reader's own inference code)
ckpts = [str(reader / f"cnxt_v0_fold{k}.pt") for k in range(3)]
df = infer.run(str(comp), "train", ckpts, studies=GOLD)
assert len(df) == len(GOLD) and df.notna().all().all(), "reader did not score every gold study"
df.to_csv(WORK / "reader-gold.csv")
print(json.dumps({"n": len(df), "files": len(files)}))
'''


def gold_uids() -> list[str]:
    rows = csv.DictReader((ROOT / "state/folds-v2-allgold.csv").open())
    return sorted(r["StudyInstanceUID"] for r in rows if r["gold_set"])


def build(slug: str) -> Path:
    gold = gold_uids()
    if len(gold) != 58:
        raise SystemExit(f"expected 58 gold studies, got {len(gold)}")
    out = ROOT / "artifacts/kaggle" / slug
    out.mkdir(parents=True, exist_ok=True)
    entry = ENTRY.replace("__GOLD__", repr(gold)).replace("__READER__", READER)
    compile(entry, "entry.py", "exec")
    (out / "entry.py").write_text(entry)
    (out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"bulsahkecici/{slug}", "title": slug, "code_file": "entry.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": False,
        "competition_sources": ["rsna-knee-abnormality-detection"], "dataset_sources": [READER],
        "kernel_sources": []}, indent=2))
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--slug", required=True)
    print(build(parser.parse_args().slug))


if __name__ == "__main__":
    main()
